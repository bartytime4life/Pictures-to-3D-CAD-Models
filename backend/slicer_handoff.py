"""Portable local slicer handoffs without native presets or machine instructions."""

import hashlib
import json
import zipfile
from pathlib import Path

from .slicers import PROGRAMS

SLICERS = {
    program_id: {
        key: program[key] for key in ("id", "name", "target_version", "release_url", "source_url")
    }
    for program_id, program in PROGRAMS.items()
}


def _readme(slicer, *, split):
    name = slicer["name"]
    part_step = (
        "2. For a split model, import the separate part-XX.3mf files as independent objects "
        "(or use the part-XX.stl alternatives). Each starts at XY zero and Z zero. "
        "Arrange and verify every piece independently; the overlapping zero origins are "
        "not a prepared plate. The combined model.3mf keeps assembly positions and touching "
        "cut faces. Avoid merging the pieces if they need to print separately.\n"
        if split
        else "2. Check the imported object's width, height, thickness and through-holes against manifest.json.\n"
    )
    return (
        f"# Pictures to CAD → {name}\n\n"
        f"Prepared for {name} {slicer['target_version']}. This version is a handoff target, "
        "not an assertion that the program is installed or has imported this model.\n\n"
        f"1. Extract this ZIP to a folder. Open model.3mf in {name} as geometry; "
        "it is a standard millimeter 3MF, not a native slicer project. "
        "If asked for a third-party 3MF import mode, choose geometry only. "
        "model.stl is the fallback; import STL coordinates as millimeters.\n"
        f"{part_step}"
        "3. Choose your exact printer, nozzle, build plate and filament preset in the slicer. "
        "The design's printer ID, nozzle, material and color are planning notes in the manifest; "
        "they are not installed presets, temperatures or filament assignments. "
        "Work in the slicer's normal Prepare/Plater view and confirm the dimensions there.\n"
        "4. Arrange on the actual printable bed, inspect fine features and holes, select orientation "
        "and supports, then slice and inspect the layer preview. Check the appropriate machine "
        "and material settings before deciding whether to export G-code.\n"
        "5. Save the reviewed native slicer project from the slicer if you want to keep its settings. "
        "Edits there do not update this workbench recipe or its fit result.\n\n"
        "The workbench has not sliced, generated G-code, contacted a printer or verified printing. "
        "A geometric envelope fit is not a support, strength, clearance or printing guarantee. "
        "Straight split cuts include no connectors, assembly clearance or kerf compensation.\n\n"
        "manifest.json records the built dimensions, planned design settings, source assembly offsets "
        "and SHA-256 hashes. Add a part's assembly_offset_mm to its normalized individual geometry "
        "to recover its original assembly position. project.json keeps the measured outline and "
        "workbench parameters. The source photograph is not included.\n\n"
        f"Official release: {slicer['release_url']}\n"
        f"Official program source: {slicer['source_url']}\n"
    )


def write_slicer_handoffs(job_dir: Path, *, name, design, dimensions, volume_mm3, parts):
    """Package only a fixed set of files generated by this build."""
    split = any("files" in part for part in parts)
    filenames = ["model.3mf", "model.stl", "project.json"]
    for part in parts:
        for kind in ("3mf", "stl"):
            if kind in part.get("files", {}):
                filenames.append(part["files"][kind])
    payload = {filename: (job_dir / filename).read_bytes() for filename in filenames}
    manifest_base = {
        "format": "pictures-to-cad-slicer-handoff",
        "version": 1,
        "name": name,
        "units": "mm",
        "design": design,
        "dimensions": dimensions,
        "volume_mm3": volume_mm3,
        "parts": [
            {
                **{key: value for key, value in part.items() if key not in ("mesh", "files")},
                **(
                    {"files": {kind: part["files"][kind] for kind in ("3mf", "stl")}}
                    if split
                    else {}
                ),
            }
            for part in parts
        ],
        "geometry_placement": "assembled",
        "individual_part_placement": "minimum XY and bottom Z at zero" if split else None,
        "native_slicer_profile": False,
        "slicing_verified": False,
        "printing_verified": False,
        "notes": [
            "The 3MF files contain geometry and millimeter units, without slicer settings or filament assignments.",
            "Printer, nozzle, material and color are planning metadata. Choose matching native presets in the slicer.",
            "The combined model preserves assembled positions. Individual split files require separate arrangement and review.",
            "A bounding-envelope fit does not establish placement, supports, material suitability, physical fit or printing success.",
            "No G-code, printer connection, print command or source photograph is included.",
        ],
    }
    for slicer_id, slicer in SLICERS.items():
        bundle_payload = {**payload, "README.md": _readme(slicer, split=split).encode("utf-8")}
        manifest = {
            **manifest_base,
            "slicer": slicer,
            "files": {
                filename: {"sha256": hashlib.sha256(data).hexdigest(), "size_bytes": len(data)}
                for filename, data in bundle_payload.items()
            },
        }
        with zipfile.ZipFile(
            job_dir / f"{slicer_id}-handoff.zip", "w", compression=zipfile.ZIP_DEFLATED
        ) as archive:
            for filename, data in bundle_payload.items():
                archive.writestr(filename, data)
            archive.writestr(
                "manifest.json", json.dumps(manifest, indent=2, allow_nan=False).encode("utf-8")
            )
